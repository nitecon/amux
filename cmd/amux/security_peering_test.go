func TestServerPeeringKeyGenerateAndCopyUseProfileIdentity(t *testing.T) {
	profile := t.TempDir()
	_, stop := startServerCommand(t, "--profile", profile, "--profile-tls-name", "127.0.0.1",
		"--secure-instance-id", uuid.NewString(), "--listen", "127.0.0.1:0", "--discovery-bind", "127.0.0.1:0")
	defer stop()
	if _, err := server.LockSecurityProfile(profile); err == nil {
		t.Fatal("server did not retain security profile ownership")
	}
	var emptyCopy bytes.Buffer
	if err := run(context.Background(), []string{"server", "peering-key", "--profile", profile, "--copy"}, &emptyCopy, io.Discard, nil); err == nil || emptyCopy.Len() != 0 {
		t.Fatalf("copy without an active invitation: output=%q err=%v", emptyCopy.String(), err)
	}

	var generated bytes.Buffer
	if err := run(context.Background(), []string{"server", "peering-key", "--profile", profile}, &generated, io.Discard, func(string) string { return "must-not-be-used" }); err != nil {
		t.Fatal(err)
	}
	key := strings.TrimSpace(generated.String())
	if key == "" || strings.Contains(key, "\n") || !strings.HasPrefix(key, "amux1.") {
		t.Fatalf("generation did not print only one invitation: %q", generated.String())
	}
	if strings.Contains(generated.String(), "must-not-be-used") || strings.Contains(generated.String(), "BEGIN CERTIFICATE") {
		t.Fatal("command printed credentials other than the invitation")
	}

	var copied bytes.Buffer
	if err := run(context.Background(), []string{"server", "peering-key", "--profile", profile, "--copy"}, &copied, io.Discard, nil); err != nil {
		t.Fatal(err)
	}
	if copied.String() != generated.String() {
		t.Fatalf("copy changed the active invitation: generated=%q copied=%q", generated.String(), copied.String())
	}
}

func TestServerPeeringKeyRejectsNonLoopbackProfileURL(t *testing.T) {
	profile := t.TempDir()
	_, stop := startServerCommand(t, "--profile", profile, "--profile-tls-name", "127.0.0.1",
		"--secure-instance-id", uuid.NewString(), "--listen", "127.0.0.1:0", "--discovery-bind", "127.0.0.1:0")
	defer stop()
	manifestPath := filepath.Join(profile, "local-client.json")
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		t.Fatal(err)
	}
	var manifest storage.LocalSecurityProfile
	if err := json.Unmarshal(data, &manifest); err != nil {
		t.Fatal(err)
	}
	manifest.URL = "https://example.com:24182"
	data, err = json.Marshal(manifest)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(manifestPath, data, 0600); err != nil {
		t.Fatal(err)
	}
	var stdout bytes.Buffer
	if err := run(context.Background(), []string{"server", "peering-key", "--profile", profile}, &stdout, io.Discard, nil); err == nil {
		t.Fatal("accepted a non-loopback local server URL")
	}
	if stdout.Len() != 0 {
		t.Fatalf("invalid profile printed output: %q", stdout.String())
	}
}
